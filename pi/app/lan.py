"""Single LAN interface contract shared by routing, DHCP, diagnostics and Wi-Fi.

The persisted choice defaults to wlan0. A corrupt choice fails closed rather
than silently applying protection to a different interface.
"""
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ETC = Path(os.environ.get('GEOBOX_ETC', '/etc/geobox'))
RUN = Path(os.environ.get('GEOBOX_RUN', '/run/geobox'))
APP = Path(__file__).resolve().parent


def interface(value):
    if not isinstance(value, str) or not re.fullmatch(r'wl[a-zA-Z0-9_-]{1,13}', value):
        raise ValueError('Invalid Wi-Fi interface')
    return value


def config():
    try:
        value = json.loads((ETC / 'wifi-radio.json').read_text())
    except FileNotFoundError:
        return {'interface': 'wlan0'}
    interface(value['interface'])
    return value


def ap_interface():
    return config()['interface']


def write(path, data, mode=0o600):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as f:
            f.write(data if isinstance(data, bytes) else data.encode())
            f.flush()
            os.fsync(f.fileno())
        os.chmod(name, mode)
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def command(args, *, data=None, timeout=40, check=True):
    result = subprocess.run(args, input=data, text=True, capture_output=True,
                            timeout=timeout, env={**os.environ, 'LANG': 'C',
                            'PATH': '/usr/sbin:/usr/bin:/sbin:/bin'})
    if check and result.returncode:
        # Commands may echo Wi-Fi credentials; never forward stderr to the UI.
        raise RuntimeError(Path(args[0]).name + ' failed (' + str(result.returncode) + ')')
    return result.stdout.strip() if check else result


def firewall(template, name):
    return template.replace('"wlan0"', '"' + interface(name) + '"')


def dhcp(name):
    name = interface(name)
    return f'''# Generated by ProxyBox; interface follows the protected LAN.
port=0
interface={name}
bind-dynamic
dhcp-authoritative
dhcp-range=10.77.0.10,10.77.0.250,255.255.255.0,12h
dhcp-option=option:router,10.77.0.1
dhcp-option=option:dns-server,10.77.0.1
dhcp-hostsfile=/var/lib/misc/geobox-dhcp-hosts
enable-ra
dhcp-range=fd77:6765:6f62:1::,ra-only,slaac,64,1h
dhcp-option=option6:dns-server
dhcp-option=option6:domain-search
ra-param={name},30,90
'''


def configure():
    """Install fail-closed firewall first, then routes and runtime DHCP config."""
    name = ap_interface()
    policy = firewall((APP / 'geobox.nft').read_text(), name)
    command(['nft', '--check', '-f', '-'], data=policy)
    command(['nft', '-f', '-'], data=policy)
    command(['sysctl', '-q', '-w', 'net.ipv4.ip_forward=1',
             'net.ipv4.conf.all.rp_filter=0', 'net.ipv4.conf.default.rp_filter=0',
             'net.ipv6.conf.all.forwarding=1'])
    for family in ('-4', '-6'):
        rules = json.loads(command(['ip', '-j', family, 'rule']))
        # Only remove the exact rules owned by this gateway, including old APs.
        for rule in rules:
            if (rule.get('priority') == 100 and str(rule.get('table')) == '100'
                    and re.fullmatch(r'wl[a-zA-Z0-9_-]{1,13}', rule.get('iif', ''))):
                command(['ip', family, 'rule', 'del', 'iif', rule['iif'],
                         'lookup', '100', 'priority', '100'])
        command(['ip', family, 'route', 'replace', 'unreachable', 'default',
                 'table', '100', 'metric', '9999'])
        command(['ip', family, 'rule', 'add', 'iif', name, 'lookup', '100', 'priority', '100'])
    for option in ('accept_ra', 'autoconf'):
        # A removable USB radio may not be enumerated yet at early boot.
        if Path('/proc/sys/net/ipv6/conf', name, option).exists():
            command(['sysctl', '-q', '-w', f'net.ipv6.conf.{name}.{option}=0'])
    write(RUN / 'lan.conf', dhcp(name), 0o644)


if __name__ == '__main__':
    import sys
    if sys.argv[1:] == ['--interface']:
        print(ap_interface())
    elif sys.argv[1:] == ['--configure']:
        # Recover an interrupted adapter transaction before NM starts at boot.
        from wifi_radio import recover_boot
        recover_boot()
        configure()
    else:
        raise SystemExit('Use --interface or --configure')
